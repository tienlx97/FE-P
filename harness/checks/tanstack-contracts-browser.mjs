import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const origin = process.env.TABLE_TEST_ORIGIN || 'http://localhost:3001';
if (!/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(origin)) throw Error('Local server only');
const run = `harness/runs/${new Date().toISOString().replace(/[:.]/g, '-')}-tanstack-contracts`;
mkdirSync(run, { recursive: true });
const exe = process.platform === 'win32' ? join(process.env.APPDATA, 'npm/node_modules/agent-browser/bin/agent-browser-win32-x64.exe') : 'agent-browser';
const b = (...args) => execFileSync(exe, ['--session', 'tanstack-contracts', ...args], { encoding: 'utf8', timeout: 45000 }).trim();
const evaluate = (code) => JSON.parse(b('eval', '-b', Buffer.from(code).toString('base64')));
const { contract, customer } = JSON.parse(readFileSync('harness/fixtures/dialogs.json', 'utf8'));
// Keep the inline mock below Windows' command-line limit; 20 rows still overflow 65vh.
const items = Array.from({ length: 20 }, (_, i) => ({ ...contract, status: 'InProgress', id: `fixture-${i}`, contractNumber: `TT-${String(i + 1).padStart(3, '0')}` }));
const route = (path, data) => b('network', 'route', '**/api/backend/api/v1/' + path, '--body', JSON.stringify(data));
execFileSync(exe, ['--session', 'tanstack-contracts', 'open', origin + '/login'], { stdio: 'inherit', timeout: 45000 });
b('cookies', 'set', 'kt-xnk-access-token', 'synthetic-table-test');
b('cookies', 'set', 'kt-xnk-session-permissions', '["users:manage","logistics:contracts:view","logistics:view"]');
b('network', 'unroute');
route('contracts/search', { page: { items, totalCount: 80, totalPages: 4, page: 1, pageSize: 25 }, totals: [{ currency: contract.currency, contractValue: 2000000, settlementValue: 2200000, paidValue: 1000000, unpaidValue: 1200000 }], settlements: items.map(row => ({contractId: row.id, settlementValue:110000, paidValue:50000, unpaidValue:60000})) });
route('customers', [customer]);
b('network', 'route', '**/api/backend/**', '--body', '[]');
b('set', 'viewport', '1440', '900');
b('open', origin + '/logistics/contracts');
b('wait', '--text', 'TT-001');
b('find', 'role', 'button', 'click', '--name', 'Tuỳ chọn hiển thị');
b('wait', '--text', 'Cột hiển thị');
b('find', 'role', 'button', 'click', '--name', 'Bỏ hiển thị Dự án', '--exact');
b('wait', '--fn', `!document.querySelector('th[data-column-key="projectName"]')`);
b('find', 'role', 'button', 'click', '--name', 'Hiển thị Dự án', '--exact');
b('wait', '--fn', `!!document.querySelector('th[data-column-key="projectName"]')`);
b('find', 'role', 'button', 'click', '--name', 'Mật độ dòng', '--exact');
b('find', 'role', 'radio', 'click', '--name', 'Gọn', '--exact');
b('find', 'role', 'button', 'click', '--name', 'Ghim cột', '--exact');
b('find', 'role', 'radio', 'click', '--name', 'Hai cột đầu tiên', '--exact');
b('screenshot', `${run}/column-options.png`);
b('press', 'Escape');
evaluate(`(() => { const row=document.querySelector('[data-table-engine="tanstack"]').tBodies[0].rows[0]; if ([...row.cells].filter(e=>getComputedStyle(e).position==='sticky').length!==3) throw Error('Pin setting not applied'); return true; })()`);
b('find', 'role', 'button', 'click', '--name', 'Tuỳ chọn hiển thị');
b('wait', '--text', 'Ghim từ đầu bảng');
b('find', 'role', 'radio', 'click', '--name', 'Cột đầu tiên', '--exact');
b('press', 'Escape');
b('screenshot', `${run}/desktop.png`);
console.log(JSON.stringify({ run }));
writeFileSync(`${run}/initial.json`, JSON.stringify(evaluate(`(() => {
  const table = document.querySelector('[data-table-engine="tanstack"]');
  if (!table) throw Error('TanStack renderer missing');
  return { rows: table.tBodies[0].rows.length, headers: [...table.querySelectorAll('th')].map(e => ({ text:e.textContent, span:e.colSpan, color:getComputedStyle(e).backgroundColor })) };
})()`), null, 2));

const checks = [];
for (const width of [1440, 390]) {
  b('set', 'viewport', String(width), '900');
  b('find', 'role', 'radio', 'click', '--name', 'Tài chính');
  b('wait', '--text', 'GIÁ TRỊ');
  evaluate(`(() => {
    const table = document.querySelector('[data-table-engine="tanstack"]');
    const scroller = table.parentElement;
    window.__headerTop = table.tHead.getBoundingClientRect().top;
    scroller.scrollTop = 250;
    scroller.scrollLeft = Math.max(0, (scroller.scrollWidth - scroller.clientWidth) / 2);
    return true;
  })()`);
  b('wait', '--fn', `document.querySelector('[data-table-engine="tanstack"]').parentElement.scrollTop > 0`);
  checks.push(evaluate(`(() => {
    const table = document.querySelector('[data-table-engine="tanstack"]');
    const scroller = table.parentElement;
    const group = [...table.querySelectorAll('th')].find(e => e.textContent === 'GIÁ TRỊ');
    if (!group || group.colSpan !== 4) throw Error('Financial header must span four columns');
    if (Math.abs(table.tHead.getBoundingClientRect().top - window.__headerTop) > 2) throw Error('Header moved on vertical scroll');
    const cells = [...table.tBodies[0].rows[0].cells];
    const pins = cells.filter(e => getComputedStyle(e).position === 'sticky');
    if (pins.length !== 2) throw Error('Expected both pinned edges');
    for (const cell of pins) {
      const header = table.querySelector('th[data-column-key="' + cell.dataset.columnKey + '"]');
      if (Math.abs(cell.getBoundingClientRect().left - header.getBoundingClientRect().left) > 2) throw Error('Pinned header/body misaligned');
      if (getComputedStyle(cell).backgroundColor !== getComputedStyle(cell.parentElement).backgroundColor) throw Error('Pinned fill differs from row');
    }
    if (new Set([...table.querySelectorAll('th')].map(e => getComputedStyle(e).backgroundColor)).size !== 1) throw Error('Header color mismatch');
    if (document.documentElement.scrollWidth > innerWidth + 1) throw Error('Page overflows horizontally');
    if (!document.body.textContent.includes('Tổng cộng')) throw Error('Totals missing');
    return { width: innerWidth, scrollTop: scroller.scrollTop, scrollLeft: scroller.scrollLeft, headerTop: table.tHead.getBoundingClientRect().top, groupSpan: group.colSpan, pins: pins.length };
  })()`));
  b('screenshot', `${run}/financial-${width}-scrolled.png`);
}
b('set', 'viewport', '1440', '900');
evaluate(`(() => { const s=document.querySelector('[data-table-engine="tanstack"]').parentElement; s.scrollTop=0; s.scrollLeft=0; return true; })()`);
b('find', 'role', 'button', 'click', '--name', 'Tuỳ chọn hiển thị');
b('wait', '--text', 'Ghim từ cuối bảng');
b('find', 'role', 'radio', 'click', '--name', 'Hai cột cuối cùng', '--exact');
b('press', 'Escape');
evaluate(`(() => { const s=document.querySelector('[data-table-engine="tanstack"]').parentElement; s.scrollLeft=s.scrollWidth; return true; })()`);
checks.push(evaluate(`(() => {
  const table=document.querySelector('[data-table-engine="tanstack"]');
  const spans=[...table.querySelectorAll('th')].filter(e=>e.textContent==='GIÁ TRỊ');
  if (spans.reduce((sum,e)=>sum+e.colSpan,0)!==4) throw Error('Split pinned group lost columns');
  const leaf=table.querySelector('th[data-column-key="unpaidValue"]');
  const body=table.querySelector('td[data-column-key="unpaidValue"]');
  if(Math.abs(leaf.getBoundingClientRect().left-body.getBoundingClientRect().left)>2) throw Error('Pinned financial leaf misaligned');
  const singleGroup=spans.find(e=>e.colSpan===1);
  if(!singleGroup || Math.abs(singleGroup.getBoundingClientRect().left-leaf.getBoundingClientRect().left)>2) throw Error('Pinned group header misaligned');
  return {splitGroupSpans:spans.map(e=>e.colSpan)};
})()`));
b('screenshot', `${run}/split-pinned-group.png`);
b('find', 'role', 'button', 'click', '--name', 'Tuỳ chọn hiển thị');
b('wait', '--text', 'Ghim từ cuối bảng');
b('find', 'role', 'radio', 'click', '--name', 'Cột cuối cùng', '--exact');
b('press', 'Escape');
b('find', 'role', 'radio', 'click', '--name', 'Mặc định');
b('find', 'placeholder', 'Tìm số HĐ, dự án...', 'fill', 'TT-001');
b('wait', '--fn', `document.querySelector('[data-table-engine="tanstack"]').tBodies[0].rows.length === 2`);
evaluate(`(() => { window.__csv = ''; const original = URL.createObjectURL; URL.createObjectURL = blob => { blob.text().then(text => window.__csv=text); return original(blob); }; return true; })()`);
b('find', 'role', 'button', 'click', '--name', 'Xuất CSV (trang hiện tại)');
b('wait', '--fn', `window.__csv.includes('TT-001')`);
checks.push(evaluate(`(() => { if (window.__csv.includes('TT-002') || window.__csv.includes('Tổng cộng')) throw Error('CSV exported hidden/totals rows'); return { csv: window.__csv }; })()`));
b('find', 'placeholder', 'Tìm số HĐ, dự án...', 'fill', 'no-match-fixture');
b('wait', '--text', 'Không tìm thấy kết quả phù hợp');
b('find', 'role', 'button', 'click', '--name', 'Xóa Tìm số HĐ, dự án...', '--exact');
b('wait', '--text', 'TT-001');
b('find', 'role', 'button', 'click', '--name', 'Bộ lọc nâng cao');
b('screenshot', `${run}/advanced-filter.png`);
b('press', 'Escape');
b('find', 'role', 'button', 'click', '--name', 'TT-001', '--exact');
b('wait', '--fn', `document.querySelector('[role="dialog"]') !== null`);
b('screenshot', `${run}/contract-dialog.png`);
b('press', 'Escape');
writeFileSync(`${run}/checks.json`, JSON.stringify(checks, null, 2));
writeFileSync(`${run}/errors.txt`, b('errors'));
console.log(JSON.stringify({ run, checks: checks.length }));
